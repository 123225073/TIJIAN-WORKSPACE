// Execute real source functions, with no bundling, app build, model or backend.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const transpile=file=>ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const url=source=>'data:text/javascript;base64,'+Buffer.from(source).toString('base64');
const productionUrl=url(transpile('src/article-production.ts'));
const {parseArticleProduction,readerProductionBody,productionBookmark,replaceProductionInstruction,replaceProductionInstructions}=await import(productionUrl);
const richSource=transpile('src/wechat-rich.ts').replace("'./article-production'",JSON.stringify(productionUrl)).replace("'dompurify'",JSON.stringify(import.meta.resolve('dompurify'))).replace("'marked'",JSON.stringify(import.meta.resolve('marked')));
const {readerArticleText}=await import(url(richSource));
const fixtures=JSON.parse(fs.readFileSync('tests/fixtures/article-production.json','utf8'));
for(const example of fixtures){
 const parsed=parseArticleProduction(example.body);
 assert.equal(parsed.body,example.body,example.name);
 assert.equal(parsed.instructions.length,example.count,example.name);
 assert.equal(parsed.readerBody,example.readerBody??example.body,example.name);
 assert.deepEqual(parsed.instructions.map(block=>block.prompt),example.prompts,example.name);
 assert.equal(readerProductionBody(example.body),parsed.readerBody);
 assert.equal(readerProductionBody(parsed.readerBody),parsed.readerBody);
 for(const block of parsed.instructions)assert.equal(example.body.slice(block.start,block.end),block.raw);
 assert.equal(readerArticleText(example.body),parsed.readerBody);
}
const photo=n=>`![已完成配图${n}](/api/studio/assets/${String(n).repeat(32)}/file)`;
const source=fixtures[0].body,blocks=parseArticleProduction(source).instructions;
const patches=blocks.map((block,index)=>({bookmark:productionBookmark(source,block.id),imageMarkdown:photo(index+1)}));
const complete=replaceProductionInstructions(source,patches);
assert.equal(parseArticleProduction(complete).instructions.length,0);
assert.equal((complete.match(/!\[/g)||[]).length,3);
assert(complete.includes('中段手工改为先看记录。'));
assert(complete.includes('正文应正常讨论提示词。'));
assert.equal(replaceProductionInstructions(source,[]),source,'failure makes no source change');
const partial=replaceProductionInstructions(source,[patches[0],patches[2]]);
assert.equal(parseArticleProduction(partial).instructions.length,1);
assert(partial.includes(blocks[1].raw),'failed image keeps exact instructions');
assert(!readerArticleText(partial).includes('图片内容建议'));
assert.throws(()=>replaceProductionInstruction(source+'用户补充。',patches[0].bookmark,photo(1)),/正文已变化/);
assert.throws(()=>replaceProductionInstruction(source,{...patches[0].bookmark,start:0},photo(1)),/已变化/);
assert.throws(()=>replaceProductionInstructions(source,[patches[0],patches[0]]),/重复替换/);
assert.throws(()=>replaceProductionInstructions(source,[patches[0],{...patches[1],imageMarkdown:'图片已生成'}]),/本地配图/);
assert.throws(()=>replaceProductionInstruction(source,patches[0].bookmark,'![外部](https://example.test/x.png)'),/本地配图/);
const withNote=fixtures[2].body,meta=parseArticleProduction(withNote).instructions;
const noteKept=replaceProductionInstruction(withNote,productionBookmark(withNote,'door-1'),photo(1));
assert(noteKept.includes(meta[1].raw));assert(!readerArticleText(noteKept).includes('作者确认'));
assert.throws(()=>productionBookmark(withNote,'editor-1'),/不存在/);
assert.throws(()=>productionBookmark(withNote+'\n\n'+meta[0].raw,'door-1'),/重复/);
const repeated=fixtures[5].body,repeatedBlocks=parseArticleProduction(repeated).instructions;
const onlySecond=replaceProductionInstruction(repeated,productionBookmark(repeated,repeatedBlocks[1].id),photo(1));
assert(onlySecond.includes(repeatedBlocks[0].raw));assert.equal(parseArticleProduction(onlySecond).instructions.length,1);
assert.equal(readerArticleText('正文[资料'+'a'.repeat(32)+']。\n[链接](https://example.test)'), '正文。\n[链接](https://example.test)');
console.log(`PASS: ${fixtures.length} shared fixtures; real readerArticleText; three images, partial failure, hand edits, notes, exact repeated blocks and atomic validation`);
