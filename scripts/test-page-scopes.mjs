import {build} from 'esbuild';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {readFileSync} from 'node:fs';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
globalThis.sessionStorage={getItem:()=>'',setItem:()=>{}};
await build({entryPoints:['src/WorkPages.tsx'],bundle:true,platform:'node',format:'cjs',packages:'external',outfile:'.runtime/page-scope-check.cjs'});
const {Today,RadarPage,BenchmarkPage}=createRequire(import.meta.url)('../.runtime/page-scope-check.cjs');
const records=[{id:'a',kind:'benchmark',title:'账号A'},{id:'b',kind:'benchmark',title:'账号B'},{id:'j1',kind:'job',title:'B账号采集',status:'failed',error:'仅属于账号B的错误',input:{action:'batch',benchmark_id:'b'}},{id:'j2',kind:'job',title:'A账号采集',status:'running',progress:'仅属于账号A的进度',input:{action:'collect',benchmark_id:'a'}},{id:'j3',kind:'job',title:'雷达更新',status:'running',progress:'仅属于雷达的进度',input:{action:'radar'}},{id:'t',kind:'task',title:'继续现有任务',messages:[],updated:'2026-09-16T10:00:00'}];
const props={list:kind=>records.filter(x=>x.kind===kind),get:id=>records.find(x=>x.id===id)};
const today=renderToStaticMarkup(React.createElement(Today,props));
assert.ok(today.includes('继续现有任务')&&today.includes('待交付')&&today.includes('开始一项工作'));
assert.ok(!today.includes('仅属于'));
const radar=renderToStaticMarkup(React.createElement(RadarPage,props));
assert.ok(radar.includes('仅属于雷达的进度'));
assert.ok(!radar.includes('仅属于账号'));
assert.ok(radar.indexOf('<h1>行业雷达')<radar.indexOf('scoped-progress'));
const benchmark=renderToStaticMarkup(React.createElement(BenchmarkPage,props));
assert.ok(benchmark.includes('仅属于账号A的进度'));
assert.ok(!benchmark.includes('仅属于账号B的错误')&&!benchmark.includes('仅属于雷达的进度'));
assert.ok(benchmark.includes('benchmark-accounts')&&benchmark.includes('benchmark-content'));
const hot=renderToStaticMarkup(React.createElement(RadarPage,{...props,initialTab:'hot'}));
for(const title of ['微博热搜','知乎热榜','头条热榜'])assert.ok(hot.includes(title));
assert.ok(!hot.includes('仅属于雷达的进度')&&!hot.includes('仅属于账号'));
const app=readFileSync('src/App.tsx','utf8');
assert.ok(!app.includes('CollectionProgress'));
assert.ok(app.includes("setError('');setForm(null);document.querySelector('.page-area')?.scrollTo(0,0)"));
console.log('PASS: home regions, radar scope, account scope, hotlist scope, heading order, no global progress panel');
